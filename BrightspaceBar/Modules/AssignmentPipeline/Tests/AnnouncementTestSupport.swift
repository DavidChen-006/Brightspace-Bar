// MARK: - Doubles

/// A scriptable `AnnouncementSource`.
///
/// Deliberately simpler than `FakeAssignmentSource`: there is no announcement
/// parser to run raw bytes through — the daemon does that parsing now — so a
/// script of values and errors is the whole job. What it keeps is the call
/// counting and the overlap high-water mark, because "the fan-out is parallel"
/// is a claim about how many fetches were in flight, never about elapsed time.
actor FakeAnnouncementSource: AnnouncementSource {

    enum Response: Sendable {
        case announcements([Announcement])
        case failure(CourseSourceError)
    }

    private var scripted: [Int: [Response]]
    private var lastServed: [Int: Response] = [:]
    private let yieldsPerFetch: Int

    private(set) var callCounts: [Int: Int] = [:]
    private(set) var maxConcurrentFetches = 0
    private var inFlight = 0

    init(_ scripted: [Int: [Response]] = [:], yieldsPerFetch: Int = 4) {
        self.scripted = scripted
        self.yieldsPerFetch = yieldsPerFetch
    }

    func callCount(for courseId: Int) -> Int {
        self.callCounts[courseId] ?? 0
    }

    var totalCallCount: Int {
        self.callCounts.values.reduce(0, +)
    }

    func fetchAnnouncements(courseId: Int) async throws -> [Announcement] {
        self.callCounts[courseId, default: 0] += 1
        self.inFlight += 1
        self.maxConcurrentFetches = max(self.maxConcurrentFetches, self.inFlight)
        defer { self.inFlight -= 1 }

        // Real suspension points, so a genuinely parallel fan-out overlaps here
        // while the test stays wall-clock free.
        for _ in 0 ..< self.yieldsPerFetch {
            await Task.yield()
        }
        self.maxConcurrentFetches = max(self.maxConcurrentFetches, self.inFlight)

        let response: Response
        if var queue = self.scripted[courseId], !queue.isEmpty {
            response = queue.removeFirst()
            self.scripted[courseId] = queue
        } else {
            response = self.lastServed[courseId] ?? .announcements([])
        }
        self.lastServed[courseId] = response

        switch response {
        case .announcements(let announcements): return announcements
        case .failure(let error): throw error
        }
    }
}

/// Builds an `Announcement` with only the fields a test is about.
func makeAnnouncement(
    id: Int,
    courseId: Int = Truth.scholarlyID,
    title: String? = nil,
    date: Date? = nil
) -> Announcement {
    Announcement(id: id, courseId: courseId, title: title ?? "Announcement \(id)", date: date)
}
