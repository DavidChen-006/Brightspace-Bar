// ─────────────────────────────────────────────────────────────────────────────
// Support for the announcements trio.
//
// A file of its own rather than additions to `DaemonTestSupport.swift` and
// `TestSupport.swift`: the announcement pipeline mirrors the assignment one
// without sharing a line of it, and the two suites should be readable — and
// breakable — independently. What IS shared is reused (`DaemonWorld`, the
// temp-root and stub machinery), through an extension rather than a copy.
// ─────────────────────────────────────────────────────────────────────────────

extension DaemonWorld {
    /// The source under test. Paths and no runner, exactly like the assignment
    /// one: every course's announcements are already inside the one `data.json`
    /// the course fetch produced.
    func announcementSource() -> DaemonAnnouncementSource {
        DaemonAnnouncementSource(paths: self.paths)
    }
}

